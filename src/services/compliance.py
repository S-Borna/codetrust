def list_frameworks() -> dict[str, str]:
    """Return supported framework IDs and their display names."""
    return dict(SUPPORTED_FRAMEWORKS)


def get_compliance_report(framework_id: str) -> ComplianceReport:
    """Generate a compliance report for the given framework.

    Args:
        framework_id: One of the supported framework identifiers.

    Returns:
        ComplianceReport with all risk mappings and evidence.

    Raises:
        ValueError: If framework_id is not supported.
    """
    if framework_id not in _FRAMEWORK_REGISTRY:
        supported = ", ".join(sorted(_FRAMEWORK_REGISTRY))
        msg = f"Unknown framework '{framework_id}'. Supported: {supported}"
        raise ValueError(msg)

    name = SUPPORTED_FRAMEWORKS[framework_id]
    risks = _FRAMEWORK_REGISTRY[framework_id]

    return ComplianceReport(
        framework_id=framework_id,
        framework_name=name,
        generated_by="CodeTrust AI Governance Platform",
        risks=list(risks),
    )


def compliance_summary(report: ComplianceReport) -> str:
    """Build human-readable summary string like '10/10 full' or '6/10 full, 4/10 partial'.

    Args:
        report: A compliance report to summarize.

    Returns:
        Summary string.
    """
    total = len(report.risks)
    full = sum(1 for r in report.risks if r.coverage_level == "full")
    partial = sum(1 for r in report.risks if r.coverage_level == "partial")
    planned = sum(1 for r in report.risks if r.coverage_level == "planned")

    parts: list[str] = [f"{full}/{total} full"]
    if partial:
        parts.append(f"{partial}/{total} partial")
    if planned:
        parts.append(f"{planned}/{total} planned")
    return ", ".join(parts)


def is_fully_compliant(framework_id: str) -> bool:
    """Check if ALL risks in a framework have full coverage.

    Args:
        framework_id: Framework identifier.

    Returns:
        True only if every risk has coverage_level == 'full'.

    Raises:
        ValueError: If framework_id is not supported.
    """
    report = get_compliance_report(framework_id)
    return all(r.coverage_level == "full" for r in report.risks)


