"""OWASP Agentic Security Initiative (ASI) 2026 compliance mapping.

Maps CodeTrust governance capabilities to recognized security frameworks.
Each mapping is verified against actual code with file paths and line numbers.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass
from typing import Literal

CoverageLevel = Literal["full", "partial", "planned"]

SUPPORTED_FRAMEWORKS: dict[str, str] = {
    "owasp-asi-2026": "OWASP Agentic Security Initiative Top 10 (2026)",
    "eu-ai-act": "EU AI Act — High-Risk AI System Requirements",
    "nist-ai-rmf": "NIST AI Risk Management Framework 1.0",
    "nis2": "NIS2 Directive (EU 2022/2555) — Art. 21 Cybersecurity Risk-Management Measures",
}


@dataclass(frozen=True)
class EvidenceItem:
    """A single piece of verified implementation evidence."""

    file: str
    function_or_component: str
    detail: str


@dataclass(frozen=True)
class RiskMapping:
    """Mapping of a single framework risk to CodeTrust capabilities."""

    risk_id: str
    risk_name: str
    description: str
    codetrust_coverage: list[str]
    coverage_level: CoverageLevel
    evidence: list[EvidenceItem]
    gap: str


@dataclass(frozen=True)
class ComplianceReport:
    """Complete compliance report for a framework."""

    framework_id: str
    framework_name: str
    generated_by: str
    risks: list[RiskMapping]

    def to_dict(self) -> dict:
        """Serialize to a JSON-safe dictionary."""
        return asdict(self)

    def to_json(self, indent: int = 2) -> str:
        """Serialize to JSON string."""
        return json.dumps(self.to_dict(), indent=indent)

    def to_markdown(self) -> str:
        """Render as a Markdown compliance report."""
        lines: list[str] = [
            f"# {self.framework_name}",
            "",
            f"**Generated by:** {self.generated_by}",
            "",
            _coverage_summary_table(self.risks),
            "",
        ]
        for risk in self.risks:
            lines.append(f"## {risk.risk_id}: {risk.risk_name}")
            lines.append("")
            lines.append(f"**Description:** {risk.description}")
            lines.append("")
            lines.append(f"**Coverage:** `{risk.coverage_level}`")
            lines.append("")
            lines.append("**CodeTrust capabilities:**")
            for cap in risk.codetrust_coverage:
                lines.append(f"- {cap}")
            lines.append("")
            if risk.evidence:
                lines.append("**Evidence:**")
                lines.append("")
                lines.append("| File | Component | Detail |")
                lines.append("|------|-----------|--------|")
                for ev in risk.evidence:
                    lines.append(f"| `{ev.file}` | {ev.function_or_component} | {ev.detail} |")
                lines.append("")
            if risk.gap:
                lines.append(f"**Gap:** {risk.gap}")
                lines.append("")
        return "\n".join(lines)


def _coverage_summary_table(risks: list[RiskMapping]) -> str:
    """Build a Markdown summary table of all risks."""
    lines = [
        "| Risk ID | Risk Name | Coverage |",
        "|---------|-----------|----------|",
    ]
    for r in risks:
        icon = {"full": "🟢", "partial": "🟡", "planned": "🔴"}[r.coverage_level]
        lines.append(f"| {r.risk_id} | {r.risk_name} | {icon} {r.coverage_level} |")
    return "\n".join(lines)


